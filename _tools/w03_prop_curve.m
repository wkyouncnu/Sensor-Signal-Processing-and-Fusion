function w03_prop_curve()
%W03_PROP_CURVE  추력 곡선 F = k n|n| 그림의 좌표를 계산해 TikZ 가 읽을 파일로 낸다.
%                Compute the coordinates of the thrust curve figure for TikZ.
%
%   matlab -batch "addpath _tools; w03_prop_curve"
%   bash _tools/tikz2svg.sh figures/src/w03-thrust-to-shafts.tex figures/w03-thrust-to-shafts.svg
%
%   왜 계산해서 넘기는가 / why the coordinates are computed rather than drawn by eye
%       이 그림의 요점은 **두 가지가 눈에 보여야 한다**는 것이다:
%         ① 원점에서 기울기가 0 이라 작은 회전수는 추력을 거의 못 낸다
%         ② 뒤로 미는 쪽이 앞으로 미는 쪽보다 **약하다** (k_neg < k_pos)
%       손으로 포물선을 그리면 둘 다 그럴듯하게만 보이고 비율이 틀린다
%       (CLAUDE.md 4 절 규칙 6-1 의 정신).
%       The point of the figure is that the slope is zero at the origin and that
%       astern is weaker than ahead. Drawn by eye, neither ratio comes out right.
%
%   내는 것 / produces: figures/src/w03-thrust-to-shafts-geo.tex

root = fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(root, '_tools'));
cfg = otter_config('base');

%  화면 축척 / the screen scale.  n 은 가로, F 는 세로 [cm]
SX = 1/19;      % rad/s -> cm
SY = 1/26;      % N     -> cm

F  = @(n) (n >= 0) .* (cfg.k_pos * n.*abs(n)) + (n < 0) .* (cfg.k_neg * n.*abs(n));
pt = @(n) sprintf('(%.4f,%.4f)', n*SX, F(n)*SY);

%  곡선 두 가지 / the two branches, sampled finely enough that TikZ draws them smooth
nf = linspace(0, cfg.n_max, 60);            % 정회전 / ahead
nr = linspace(cfg.n_min, 0, 60);            % 역회전 / astern
ahead  = strjoin(arrayfun(@(x) pt(x), nf, 'uni', 0), ' -- ');
astern = strjoin(arrayfun(@(x) pt(x), nr, 'uni', 0), ' -- ');

%  익명함수는 L 을 **만들 때의 값으로 잡아** 두므로 add = @(s)[L,{s}] 로는 한 줄만 남는다.
%  실제로 그렇게 썼다가 geo 파일에 마지막 \def 하나만 들어갔다 (2026-10-13).
%  An anonymous function captures L by value, so add = @(s)[L,{s}] keeps only the
%  last line. That is exactly what happened: the geo file came out with one \def.
L = {};
L{end+1} = sprintf('%% 자동 생성 — w03_prop_curve.m 가 만든다. 손으로 고치지 않는다.');
L{end+1} = sprintf('%% generated by _tools/w03_prop_curve.m; do not edit by hand');
L{end+1} = sprintf('\\def\\kpos{%.5f}', cfg.k_pos);
L{end+1} = sprintf('\\def\\kneg{%.5f}', cfg.k_neg);
L{end+1} = sprintf('\\def\\nmax{%.1f}',  cfg.n_max);
L{end+1} = sprintf('\\def\\nmin{%.1f}',  cfg.n_min);
L{end+1} = sprintf('\\def\\Fmax{%.1f}',  cfg.k_pos*cfg.n_max^2);
L{end+1} = sprintf('\\def\\Fmin{%.1f}', -cfg.k_neg*cfg.n_min^2);
L{end+1} = sprintf('\\def\\ypont{%.4f}', cfg.y_pont);
%  축 끝과 눈금 / the ends of the axes and the ticks
L{end+1} = sprintf('\\def\\axL{%.4f}', -115*SX);
L{end+1} = sprintf('\\def\\axR{%.4f}',  118*SX);
L{end+1} = sprintf('\\def\\axD{%.4f}',  -80*SY);
L{end+1} = sprintf('\\def\\axU{%.4f}',  135*SY);
L{end+1} = sprintf('\\def\\nmaxx{%.4f}', cfg.n_max*SX);
L{end+1} = sprintf('\\def\\nminx{%.4f}', cfg.n_min*SX);
L{end+1} = sprintf('\\def\\Fmaxy{%.4f}', cfg.k_pos*cfg.n_max^2*SY);
L{end+1} = sprintf('\\def\\Fminy{%.4f}', -cfg.k_neg*cfg.n_min^2*SY);
%  읽어 내는 예: F = 38.16 N 일 때의 n (5-7 절 '직진' 행) / the worked reading
Fw = 38.16;  nw = sqrt(Fw/cfg.k_pos);
L{end+1} = sprintf('\\def\\Fw{%.2f}',  Fw);
L{end+1} = sprintf('\\def\\nw{%.2f}',  nw);
L{end+1} = sprintf('\\def\\Fwy{%.4f}', Fw*SY);
L{end+1} = sprintf('\\def\\nwx{%.4f}', nw*SX);
L{end+1} = sprintf('\\def\\curveAhead{%s}',  ahead);
L{end+1} = sprintf('\\def\\curveAstern{%s}', astern);

out = fullfile(root, 'figures', 'src', 'w03-thrust-to-shafts-geo.tex');
f = fopen(out, 'w');  fprintf(f, '%s\n', L{:});  fclose(f);

fprintf('\n  w03_prop_curve\n');
fprintf('    k_pos %.5f   k_neg %.5f   (astern weaker by %.1f %%)\n', ...
        cfg.k_pos, cfg.k_neg, 100*(1 - cfg.k_neg/cfg.k_pos));
fprintf('    n in [%.1f, %.1f] rad/s  ->  F in [%.1f, %.1f] N\n', ...
        cfg.n_min, cfg.n_max, -cfg.k_neg*cfg.n_min^2, cfg.k_pos*cfg.n_max^2);
fprintf('    worked reading: F = %.2f N  ->  n = sqrt(F/k_pos) = %.2f rad/s\n', Fw, nw);
fprintf('    wrote %s\n\n', out);
end
